export const HUGE_ICON_NAMES = Object.freeze(Object.keys(iconsByName));

function resolveIcon(name: IconName): IconSvgElement {
  return iconsByName[name] ?? Search01IconSvg;
}

const iconCache = new Map<string, HugeIcon>();

function createHugeIcon(name: IconName): HugeIcon {
  const cached = iconCache.get(name);
  if (cached) return cached;

  const Icon = React.forwardRef<SVGSVGElement, HugeIconProps>(
    ({ strokeWidth, ...props }, ref) => (
      <HugeiconsIcon
        ref={ref}
        icon={resolveIcon(name)}
        strokeWidth={typeof strokeWidth === "string" ? Number(strokeWidth) : strokeWidth}
        {...props}
      />
    ),
  );
  Icon.displayName = `HugeIcon(${name})`;
  iconCache.set(name, Icon);
  return Icon;
}

/** Lazily creates semantic components without retaining the former icon API. */
export const Hugeicons = new Proxy({} as Record<string, HugeIcon>, {
  get: (_target, property) => typeof property === "string" ? createHugeIcon(property) : undefined,
});

export const DynamicIcon = React.forwardRef<SVGSVGElement, HugeIconProps & { name: IconName }>(
  ({ name, ...props }, ref) => {
    const Icon = createHugeIcon(name);
    return <Icon ref={ref} {...props} />;
  },
);
DynamicIcon.displayName = "DynamicHugeIcon";
